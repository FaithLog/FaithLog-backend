CREATE TABLE companion_designs (
 design_id VARCHAR(100) PRIMARY KEY, species_code VARCHAR(60) NOT NULL, species_name VARCHAR(100) NOT NULL,
 style_code VARCHAR(40) NOT NULL, name VARCHAR(160) NOT NULL,
 rarity VARCHAR(16) NOT NULL CHECK(rarity IN ('COMMON','UNCOMMON','RARE','EPIC','UNIQUE')),
 asset_key VARCHAR(100) NOT NULL UNIQUE, catalog_order INTEGER NOT NULL UNIQUE, active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE user_companions (
 user_id BIGINT NOT NULL REFERENCES users(id), design_id VARCHAR(100) NOT NULL REFERENCES companion_designs(design_id),
 quantity BIGINT NOT NULL CHECK(quantity>=1), acquired_at TIMESTAMPTZ NOT NULL,
 PRIMARY KEY(user_id,design_id)
);
CREATE INDEX ix_user_companions_design ON user_companions(design_id);
CREATE TABLE backgrounds (
 background_id VARCHAR(40) PRIMARY KEY,name VARCHAR(100) NOT NULL,description VARCHAR(255) NOT NULL,
 asset_key VARCHAR(100) NOT NULL UNIQUE, active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE user_backgrounds (
 user_id BIGINT NOT NULL REFERENCES users(id),background_id VARCHAR(40) NOT NULL REFERENCES backgrounds(background_id),
 acquired_at TIMESTAMPTZ NOT NULL,PRIMARY KEY(user_id,background_id)
);
CREATE INDEX ix_user_backgrounds_background ON user_backgrounds(background_id);
