CREATE TABLE point_wallets (
 user_id BIGINT PRIMARY KEY REFERENCES users(id),
 balance BIGINT NOT NULL DEFAULT 0 CHECK(balance >= 0),
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE point_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES point_wallets(user_id),
 delta BIGINT NOT NULL CHECK(delta <> 0),
 balance_after BIGINT NOT NULL CHECK(balance_after >= 0),
 business_key VARCHAR(160) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT uk_point_transaction_business UNIQUE(user_id,business_key)
);
CREATE INDEX ix_point_transactions_user_id_desc ON point_transactions(user_id,id DESC);
ALTER TABLE point_wallets ENABLE ROW LEVEL SECURITY;
ALTER TABLE point_transactions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON point_wallets,point_transactions FROM PUBLIC;
REVOKE ALL ON SEQUENCE point_transactions_id_seq FROM PUBLIC;
DO $$ DECLARE role_name TEXT; BEGIN
 FOREACH role_name IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
  IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
   EXECUTE format('REVOKE ALL ON point_wallets,point_transactions FROM %I',role_name);
   EXECUTE format('REVOKE ALL ON SEQUENCE point_transactions_id_seq FROM %I',role_name);
  END IF;
 END LOOP;
END $$;
