CREATE TABLE calendar_daily_rewards (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 campus_id BIGINT NOT NULL REFERENCES campuses(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 record_date DATE NOT NULL,
 mission VARCHAR(16) NOT NULL CHECK (mission IN ('QUIET_TIME','PRAYER','BIBLE')),
 calendar_checked BOOLEAN NOT NULL DEFAULT FALSE,
 claimed_at TIMESTAMP WITH TIME ZONE,
 points INTEGER NOT NULL DEFAULT 0 CHECK (points IN (0,30)),
 CONSTRAINT uk_calendar_reward_scope UNIQUE (campus_id,user_id,record_date,mission),
 CONSTRAINT ck_calendar_reward_claim CHECK ((claimed_at IS NULL AND points=0) OR (claimed_at IS NOT NULL AND points=30))
);
